"""Builds docs/TEST_PLAN.md from the automated test-suite.

Each automated test documents itself with a docstring of the form
    TC-ID | scenario | input | expected result
This script runs pytest, reads the real pass/fail outcome of every test and writes the
table (Test Case ID, Scenario, Input, Expected Result, Actual Result, Status), so the
test plan in the report always reflects an actual run.

    cd docs && python build_test_plan.py
"""
import ast
import glob
import os
import subprocess
import sys
import xml.etree.ElementTree as ET
from datetime import date

HERE = os.path.dirname(os.path.abspath(__file__))
BACKEND = os.path.join(os.path.dirname(HERE), "backend")
TESTS = os.path.join(BACKEND, "tests")

MANUAL_UI_CASES = [
    ("UI-01", "Splash screen then login", "Launch the app with no saved session", "Splash is shown, then the Login screen"),
    ("UI-02", "Register from the app", "Name, new email, password", "Account created, user lands on My Trips"),
    ("UI-03", "Login validation messages", "Empty fields / bad email / wrong password", "Inline validation or the server message is shown"),
    ("UI-04", "Create trip and share code", "Goa Trip 2026, Goa, 10-15 Dec", "Trip appears in My Trips, invite code can be copied"),
    ("UI-05", "Join trip from a second device", "Invite code typed in lower case", "Trip appears for the second user"),
    ("UI-06", "Add expense - equal split", "Rs 3600, 6 members ticked", "Expense listed, dashboard totals update for all members"),
    ("UI-07", "Add expense - custom split", "Amounts not matching total", "Remaining amount shown in red, Save is rejected"),
    ("UI-08", "Add expense - percentage split", "Percentages totalling 100", "Per-member rupee amounts are shown, expense saved"),
    ("UI-09", "Settlement screen", "Open Final Settlement, tap Calculate", "You owe / You receive / Suggested payments are listed"),
    ("UI-10", "Mark payment as paid", "Tap Mark paid on a suggested payment", "Status chip changes to Paid, remaining balance updates"),
    ("UI-11", "Logout", "Profile > Logout, then press back", "Returns to Login, protected screens are not reachable"),
]


def collect_cases():
    cases = {}
    for path in sorted(glob.glob(os.path.join(TESTS, "test_*.py"))):
        tree = ast.parse(open(path, encoding="utf-8").read())
        for node in ast.walk(tree):
            if isinstance(node, ast.FunctionDef) and node.name.startswith("test_"):
                doc = ast.get_docstring(node) or ""
                parts = [p.strip() for p in doc.split("|")]
                if len(parts) == 4 and parts[0].startswith("TC-"):
                    cases[node.name] = dict(id=parts[0], scenario=parts[1], inp=parts[2],
                                            expected=parts[3], file=os.path.basename(path))
    return cases


def run_pytest():
    xml_path = os.path.join(HERE, "pytest_results.xml")
    proc = subprocess.run([sys.executable, "-m", "pytest", "-q", f"--junitxml={xml_path}", "-p", "no:cacheprovider"],
                          cwd=BACKEND, capture_output=True, text=True)
    results = {}
    for tc in ET.parse(xml_path).getroot().iter("testcase"):
        base = tc.get("name").split("[")[0]
        failure = tc.find("failure")
        error = tc.find("error")
        problem = failure if failure is not None else error
        prev = results.get(base)
        if problem is not None:
            msg = (problem.get("message") or "failed").splitlines()[0][:120]
            results[base] = ("Fail", msg)
        elif prev is None:
            results[base] = ("Pass", "Matched the expected result")
    os.remove(xml_path)
    return results, proc.stdout.strip().splitlines()[-1]


def esc(text):
    return text.replace("|", "\\|")


def main():
    cases = collect_cases()
    results, summary = run_pytest()
    rows = sorted(cases.items(), key=lambda kv: kv[1]["id"])
    passed = sum(1 for name, _ in rows if results.get(name, ("Not run",))[0] == "Pass")

    out = [
        "# TripSplit - Test Plan and Results",
        "",
        f"_Generated by `docs/build_test_plan.py` on {date.today().isoformat()} from a real run of the automated suite._",
        "",
        f"**Automated run:** `{summary}`  ",
        f"**Documented test cases:** {len(rows)} ({passed} passed)",
        "",
        "The API tests run against SQLite (a schema twin of the MySQL schema, `backend/tests/schema_sqlite.sql`) "
        "so they need no database server. They exercise all application logic and SQL, but MySQL-specific "
        "behaviour (CHECK enforcement on 8.0.16+, `SELECT ... FOR UPDATE`, DECIMAL storage) should also be "
        "confirmed once on a real MySQL server using `database/schema.sql`, `backend/seed_demo.py` and "
        "`database/sample_queries.sql`.",
        "",
        "## A. Automated test cases (positive and negative)",
        "",
        "| Test Case ID | Test Scenario | Input | Expected Result | Actual Result | Status |",
        "|---|---|---|---|---|---|",
    ]
    for name, c in rows:
        status, actual = results.get(name, ("Not run", "Test did not execute"))
        out.append(f"| {c['id']} | {esc(c['scenario'])} | {esc(c['inp'])} | {esc(c['expected'])} | "
                   f"{esc(actual)} | {status} |")

    out += ["", "## B. Manual UI test cases (Flutter app)", "",
            "These must be run on an emulator or phone against a running backend. "
            "They have **not** been executed yet, so Actual Result and Status are left to be filled in during testing.",
            "",
            "| Test Case ID | Test Scenario | Input | Expected Result | Actual Result | Status |",
            "|---|---|---|---|---|---|"]
    for tid, scenario, inp, expected in MANUAL_UI_CASES:
        out.append(f"| {tid} | {scenario} | {inp} | {expected} |  | Pending |")

    path = os.path.join(HERE, "TEST_PLAN.md")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"Wrote {path}: {len(rows)} automated cases, {passed} passed. {summary}")


if __name__ == "__main__":
    main()
